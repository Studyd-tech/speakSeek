import {join} from 'node:path';
import {Store,seed} from './store.js';
import {Model} from './model.js';
import {Notify,cliRunner} from './notify.js';
import {makeApp} from './server.js';
import {root,ingestToken} from './config.js';
const store=new Store(join(root,'.local','agentpulse.sqlite'));store.recover();
if(!store.session('sample-checkout'))seed(store);
const notify=new Notify(cliRunner(process.env.NOTIFY_BIN??'notify'));
const model=new Model({key:process.env.BELWEAVE_API_KEY,base:process.env.BELWEAVE_BASE_URL,model:process.env.BELWEAVE_MODEL});
const app=makeApp({store,notify,model,ingestToken:ingestToken(),webDir:join(root,'dist','web'),outputDir:join(root,'demo-output'),notifications:process.env.AGENTPULSE_NOTIFICATIONS==='true'});
let port=Number(process.env.AGENTPULSE_PORT??5177);if(!Number.isInteger(port)||port<1024||port>65535)throw new Error('Invalid AGENTPULSE_PORT');
app.server.on('error',(e:NodeJS.ErrnoException)=>{if(e.code==='EADDRINUSE'&&port<5190){port++;app.server.listen(port,'127.0.0.1')}else{console.error('AgentPulse could not start:',e.code);process.exitCode=1;store.close()}});
app.server.listen(port,'127.0.0.1',()=>console.log(`AgentPulse running at http://127.0.0.1:${port}`));
void notify.check();
const timer=setInterval(()=>app.approvals.expire(),5000);timer.unref();
for(const signal of ['SIGINT','SIGTERM'] as const)process.on(signal,()=>{clearInterval(timer);app.server.close(()=>{store.close();process.exit(0)});setTimeout(()=>process.exit(0),1500).unref()});
